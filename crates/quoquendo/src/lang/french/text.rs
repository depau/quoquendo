impl French {
    /// 0x10002a70 (argument 4 `c`): whether a word can be read as it is.
    /// An apostrophe or an accented letter: yes. Otherwise, in capitals,
    /// two letters are spelled, three only read as vowel-consonant-vowel
    /// or consonant-vowel-consonant (`est` too), four not with three
    /// consonants after at most one vowel; and a word needs a vowel.
    pub(crate) fn pronunciabile_c(&self, word: &[u8], c: u8) -> bool {
        let mut w = Vec::new();
        let mut upper = true;
        for &ch in word.iter().take(0x3f) {
            if ch == b'\'' || self.flags(ch) & 0x80 != 0 {
                return true;
            }
            if self.flags(ch) & 0x20 == 0 {
                upper = false;
            }
            w.push(self.lower(ch));
        }
        if c != 0 {
            return false;
        }
        let vow = |k: usize| self.is_vowel(super::b(&w, k as isize));
        let cons = |k: usize| self.flags(super::b(&w, k as isize)) & 0x8 != 0;
        if upper {
            match w.len() {
                2 => return false,
                3 => {
                    if w == b"est" || (vow(0) && vow(2) && !vow(1)) {
                        return true;
                    }
                    return cons(0) && cons(2) && vow(1);
                }
                4 => {
                    let mut k = 0;
                    while k < 4 && vow(k) {
                        k += 1;
                    }
                    if k < 2 && cons(k) && cons(k + 1) && cons(k + 2) {
                        return false;
                    }
                }
                _ => {}
            }
        }
        w.iter().any(|&ch| self.is_vowel(ch))
    }

    /// 0x100025d0
    pub(crate) fn symbol_name(&self, c: u8, mode: u8) -> Vec<u8> {
        SYMBOLS
            .iter()
            .find(|&&(ch, _, _)| ch == c)
            .map_or(Vec::new(), |&(_, a0, a1)| self.s(if mode != 0 { a1 } else { a0 }).to_vec())
    }
}

/// 0x100043f0: grave accents, apostrophes, 0x92 and 0xb4 become `'`.
pub(crate) fn normalizza_accento(w: &mut [u8]) {
    for c in w.iter_mut() {
        if matches!(*c, b'`' | b'\'' | 0x92 | 0xb4) {
            *c = b'\'';
        }
    }
}
